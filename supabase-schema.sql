create table if not exists public.items (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  name text not null,
  category text not null default 'Componente',
  brand text not null default '',
  model text not null default '',
  sku text not null default '',
  quantity integer not null default 0 check (quantity >= 0),
  minimum_quantity integer not null default 0 check (minimum_quantity >= 0),
  box text not null default '',
  shelf text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.items enable row level security;

drop policy if exists "Users can read their own items" on public.items;
create policy "Users can read their own items"
  on public.items for select to authenticated using ((select auth.uid()) = owner_id);

drop policy if exists "Users can add their own items" on public.items;
create policy "Users can add their own items"
  on public.items for insert to authenticated with check ((select auth.uid()) = owner_id);

drop policy if exists "Users can update their own items" on public.items;
create policy "Users can update their own items"
  on public.items for update to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

drop policy if exists "Users can delete their own items" on public.items;
create policy "Users can delete their own items"
  on public.items for delete to authenticated using ((select auth.uid()) = owner_id);

create index if not exists items_owner_name_idx on public.items (owner_id, name);